// Bundles the MCP protocol handler and the calculators PUBLISHED IN THIS BUILD into .mcp/, which functions/mcp.ts imports.
// Runs inside `npm run build`, before Cloudflare compiles the Functions, so the bundle always matches the site.
//
// Why only the published ones, and lazily: the first version built all 1,171 calculators when the Function loaded, which
// takes over a second of CPU, and Cloudflare refused it ("Script startup exceeded CPU time limit"). Now the entry holds one
// loader per published calculator; a calculator is built the first time someone asks for it.
//
// Known limit, for when cohorts 2 and 3 publish: a generator file builds all of its calculators in one call (finance.ts took
// about 300 ms in a cold Node run). On a Worker plan with a 10 ms CPU limit that first call could be refused. The build prints
// what it measured so the decision is made with numbers (README, "MCP server").
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { build } from 'vite';
import { getPublishableCalculators } from '../src/lib/registry';
import type { CalculatorConfig } from '../src/lib/types';

export const OUT_DIR = '.mcp';
export const SRC_DIR = '.mcp-src';
export const OUT_FILE = 'mcp-core.mjs';
/** The Worker size limit on the free plan is 3 MB compressed; stop well before it so growth to about 4,000 calculators still fits. */
export const MAX_GZIP_BYTES = 2.4 * 1024 * 1024;

const generators = import.meta.glob<{ default: () => CalculatorConfig[] }>('../src/generators/*.ts', { eager: true });

function sizeOf(dir: string): { raw: number; gzip: number } {
  let raw = 0;
  let gzip = 0;
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      const inner = sizeOf(path);
      raw += inner.raw;
      gzip += inner.gzip;
    } else {
      const bytes = readFileSync(path);
      raw += bytes.length;
      gzip += gzipSync(bytes).length;
    }
  }
  return { raw, gzip };
}

export default async function main(): Promise<number> {
  const slugs = getPublishableCalculators().map((c) => c.slug);
  const handWritten = new Set(
    readdirSync('src/calculators')
      .filter((f) => f.endsWith('.ts'))
      .map((f) => f.slice(0, -3)),
  );

  // Which generator file owns each published calculator that is not hand-written.
  const owner = new Map<string, string>();
  const timings = new Map<string, number>();
  const generated = slugs.filter((s) => !handWritten.has(s));
  if (generated.length) {
    for (const [path, mod] of Object.entries(generators)) {
      const file = path.split('/').pop()!.replace(/\.ts$/, '');
      const started = performance.now();
      const configs = mod.default();
      const ms = performance.now() - started;
      let used = false;
      for (const c of configs) {
        if (!generated.includes(c.slug) || owner.has(c.slug)) continue;
        owner.set(c.slug, file);
        used = true;
      }
      if (used) timings.set(file, ms);
    }
  }

  const lines = [
    '// Generated by scripts/build-mcp.ts. Do not edit; do not commit.',
    "import { createCore, fromGenerator, fromModule } from '../src/mcp/core';",
    '',
    'export const core = createCore({',
    ...slugs.map((slug) => {
      if (handWritten.has(slug)) return `  ${JSON.stringify(slug)}: fromModule(() => import('../src/calculators/${slug}')),`;
      const file = owner.get(slug);
      if (!file) throw new Error(`build-mcp: published calculator ${slug} is in neither src/calculators nor a generator`);
      return `  ${JSON.stringify(slug)}: fromGenerator(${JSON.stringify(file)}, () => import('../src/generators/${file}'), ${JSON.stringify(slug)}),`;
    }),
    '});',
    'export const MAX_BODY_BYTES = 16 * 1024;',
    'export const handleMcp = core.handleMcp;',
    '',
  ];
  mkdirSync(SRC_DIR, { recursive: true });
  writeFileSync(join(SRC_DIR, 'entry.ts'), lines.join('\n'));

  await build({
    configFile: false,
    root: process.cwd(),
    publicDir: false, // do not copy public/ (the site's images and _headers) into the Function bundle
    logLevel: 'warn',
    build: {
      ssr: join(SRC_DIR, 'entry.ts'),
      outDir: OUT_DIR,
      emptyOutDir: true,
      minify: true,
      target: 'es2022',
      rollupOptions: { output: { entryFileNames: OUT_FILE, format: 'es' } },
    },
    ssr: { noExternal: true, target: 'webworker' },
  });
  if (!existsSync(join(OUT_DIR, OUT_FILE))) throw new Error(`build-mcp: ${OUT_DIR}/${OUT_FILE} was not written`);

  const { raw, gzip } = sizeOf(OUT_DIR);
  const kb = (n: number) => `${(n / 1024).toFixed(0)} KB`;
  if (gzip > MAX_GZIP_BYTES) {
    console.error(`build-mcp FAILED: the MCP bundle is ${kb(gzip)} gzipped, over the ${kb(MAX_GZIP_BYTES)} budget (a Worker may be 3 MB compressed).`);
    return 1;
  }
  console.log(`build-mcp OK: ${slugs.length} published calculators, ${kb(raw)} (${kb(gzip)} gzipped) of ${kb(MAX_GZIP_BYTES)} budget.`);
  for (const [file, ms] of [...timings].sort((a, b) => b[1] - a[1])) console.log(`  generator ${file}: first call ${ms.toFixed(0)} ms (cold, Node)`);
  return 0;
}
